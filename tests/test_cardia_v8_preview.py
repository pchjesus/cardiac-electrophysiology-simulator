#!/usr/bin/env python3
"""Standalone smoke test for the review branch. This does not certify physiology."""
from pathlib import Path
from playwright.sync_api import sync_playwright

html = (Path(__file__).resolve().parents[1] / "prototypes/cardia-v8/index.html").read_text(encoding="utf-8")
checks=[]
def verify(ok, label):
    assert ok, label
    checks.append(label)

with sync_playwright() as p:
    browser = p.chromium.launch()
    page = browser.new_page(viewport={"width": 1440, "height": 900})
    errors=[]
    page.on("pageerror", lambda e: errors.append(str(e)))
    page.set_content(html, wait_until="load")
    verify(page.evaluate("CardiaV7.ready && CardiaV8.ready"), "v7 engine adapter + v8 UI loaded")
    verify(page.locator("#v7Stage #heartSVG").count()==1, "native heart node preserved")
    verify(page.locator("#v7Wave #ecgCanvas").count()==1, "native ECG canvas preserved")
    verify(page.locator("#v113TabClinical").is_disabled(), "clinical review gate preserved")
    verify(page.locator("#dashboardWiggersBtn").is_hidden(), "Wiggers hidden by default")
    page.locator("#playBtn").click()
    verify(page.evaluate("heartState.playing"), "native clock starts")
    page.locator("#pauseBtn").click()
    verify(not page.evaluate("heartState.playing"), "native clock pauses")
    page.locator("#mechanicalModeBtn").click()
    verify(page.evaluate("CardiacDashboard.view==='mechanical'"), "valve view")
    page.locator("#electricalModeBtn").click()
    verify(page.evaluate("CardiacDashboard.view==='electrical'"), "electrical view")
    page.locator("#v113TabLearning").click()
    page.wait_for_function("CardiacMainTabs.active==='learning'")
    verify(page.locator("#v8Learning").is_visible(), "inquiry learning displayed")
    verify(page.locator("#v7Learn").is_hidden(), "v7 learning replaced visually")
    verify(page.locator(".v8-path-item").count()==5, "optional Wiggers lesson hidden")
    page.locator("#v8StepObserve").click()
    verify(page.evaluate("CardiaV8.phase==='observe'"), "observe phase")
    page.locator("#v8StepCheck").click()
    verify(page.evaluate("CardiaV8.phase==='check'"), "formative review phase")
    page.locator('.v8-answer[data-answer="0"]').click()
    verify("다시 연결" in page.locator(".v8-feedback").inner_text(), "incorrect answer feedback")
    page.locator('.v8-answer[data-answer="1"]').click()
    verify("정확해요" in page.locator(".v8-feedback").inner_text(), "correct answer feedback")
    verify(not page.evaluate("CardiacCourseV113.completedUnitIds.length"), "practice does not fake native completion")
    page.locator('#v8LessonList [data-unit="unit-mechanics"]').click()
    verify(page.evaluate("CardiacCourseV113.activeUnitId==='unit-mechanics'"), "native unit selection")
    page.locator("#v8StepObserve").click()
    page.locator("#v8LaunchLab").click()
    page.wait_for_function("CardiacMainTabs.active==='simulator'")
    verify(page.evaluate("CardiacDashboard.view==='mechanical'"), "lesson opens related native view")
    verify(not page.evaluate("heartState.playing"), "switching main screens pauses native clock")
    page.locator("#v7HeaderSettings").click()
    page.locator("#ps6WiggersToggle").check()
    page.locator("#ps6SettingsDone").click()
    page.locator("#v113TabLearning").click()
    page.wait_for_function("CardiacMainTabs.active==='learning'")
    verify(page.locator('#v8LessonList [data-unit="unit-wiggers"]').count()==1, "opt-in reveals Wiggers lesson")
    page.locator('#v8LessonList [data-unit="unit-wiggers"]').click()
    page.locator("#v8StepObserve").click()
    page.locator("#v8LaunchLab").click()
    page.wait_for_function("CardiacMainTabs.active==='simulator'")
    verify(page.evaluate("CardiacDashboard.view==='wiggers'"), "optional view works")
    page.locator("#v7HeaderSettings").click()
    page.locator("#ps6WiggersToggle").uncheck()
    page.locator("#ps6SettingsDone").click()
    verify(page.evaluate("CardiacDashboard.view==='electrical'"), "opt-out restores electrical view")
    for width in [320, 390, 768, 1440]:
        page.set_viewport_size({"width":width,"height":900})
        verify(page.evaluate("document.documentElement.scrollWidth <= innerWidth+2"), f"no horizontal overflow {width}")
    page.emulate_media(reduced_motion="reduce")
    verify(page.evaluate("matchMedia('(prefers-reduced-motion: reduce)').matches"), "reduced motion")
    verify(not errors, "no JavaScript exceptions: " + str(errors))
    browser.close()
print("CARDIA v8 integration smoke PASS:", len(checks), "checks")
